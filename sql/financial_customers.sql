create table financial_customers (
  customer_id number generated by default as identity primary key,
  customer_number varchar2(30 char) not null unique,
  legal_name varchar2(160 char) not null,
  customer_type varchar2(30 char) not null,
  country_code char(2 char) not null,
  onboarding_date date not null,
  kyc_status varchar2(30 char) not null,
  risk_rating varchar2(20 char) not null,
  annual_income_usd number(14,2),
  assets_under_management_usd number(16,2),
  credit_score number(3),
  is_pep char(1 char) default 'N' not null,
  aml_watchlist_status varchar2(30 char) default 'CLEAR' not null,
  preferred_channel varchar2(30 char),
  relationship_manager varchar2(120 char),
  created_at timestamp default systimestamp not null,
  updated_at timestamp default systimestamp not null,
  constraint financial_customers_type_ck check (customer_type in ('RETAIL', 'SME', 'CORPORATE', 'PRIVATE_BANKING')),
  constraint financial_customers_kyc_ck check (kyc_status in ('PENDING', 'VERIFIED', 'REVIEW_REQUIRED', 'REJECTED')),
  constraint financial_customers_risk_ck check (risk_rating in ('LOW', 'MEDIUM', 'HIGH')),
  constraint financial_customers_pep_ck check (is_pep in ('Y', 'N')),
  constraint financial_customers_aml_ck check (aml_watchlist_status in ('CLEAR', 'POTENTIAL_MATCH', 'MATCH'))
);

